class AppServerError(RuntimeError):
    """Base class for bounded App Server failures."""


class AppServerUnavailable(AppServerError):
    """Raised when the installed capability cannot satisfy the adapter contract."""


class AppServerProtocolError(AppServerError):
    """Raised when an App Server frame violates the JSON-RPC contract."""


class AppServerTimeout(AppServerError):
    """Raised when a bounded App Server request or event wait expires."""


class AppServerProcessLost(AppServerError):
    """Raised when the App Server subprocess exits or closes its output."""


class AppServerRPCError(AppServerError):
    """Raised for a JSON-RPC error response returned by App Server."""

    def __init__(self, code: int | str, message: str, data: Any = None):
        """Store the bounded server error fields."""

        self.code = code
        self.message = str(message)
        self.data = data
        super().__init__(f"App Server RPC error {code}: {self.message}")


def _now() -> str:
    return datetime.now(UTC).isoformat(timespec="microseconds").replace("+00:00", "Z")


def _strict_json(value: Any, *, limit: int, name: str) -> bytes:
    """Serialize a finite JSON value and apply a byte bound."""

    try:
        encoded = json.dumps(
            value,
            ensure_ascii=False,
            allow_nan=False,
            separators=(",", ":"),
        ).encode("utf-8")
    except (TypeError, ValueError, UnicodeError) as exc:
        raise AppServerProtocolError(f"{name} is not strict JSON: {exc}") from exc
    if len(encoded) > limit:
        raise AppServerProtocolError(f"{name} exceeds {limit} bytes")
    return encoded


def _digest(value: Any) -> str:
    return hashlib.sha256(
        _strict_json(value, limit=MAX_APP_SERVER_FRAME_BYTES, name="digest input")
    ).hexdigest()


def _text(value: Any, *, name: str, limit: int = 4_096) -> str:
    if not isinstance(value, str) or not value.strip():
        raise AppServerProtocolError(f"{name} must be non-empty")
    if len(value) > limit:
        raise AppServerProtocolError(f"{name} exceeds {limit} characters")
    return value


def _finite_positive(value: float, *, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{name} must be a finite positive number")
    result = float(value)
    if not math.isfinite(result) or result <= 0:
        raise ValueError(f"{name} must be a finite positive number")
    return result


@dataclass(frozen=True, slots=True)
class AppServerFrame:
    """One received JSONL frame with monotonic ordering metadata."""

    sequence: int
    message: Mapping[str, Any]
    received_at: str = field(default_factory=_now)


@dataclass(frozen=True, slots=True)
class AppServerMCPConfig:
    """Per-process external MCP configuration for a private audit bridge."""

    bridge: AuditMCPBridge
    name: str = "robot_sf_audit"
    required: bool = True

    def __post_init__(self) -> None:
        """Validate the server name before building ``-c`` overrides."""

        if not self.name or any(
            char not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-"
            for char in self.name
        ):
            raise ValueError("MCP server name must contain only letters, digits, '_' or '-'")

    def config_overrides(self) -> tuple[str, ...]:
        """Return ``codex -c`` overrides without embedding session secrets."""

        command = self.bridge.command()
        prefix = f"mcp_servers.{self.name}"
        env_vars = [
            "ROBOT_SF_AUDIT_MCP_SESSION_ID",
            "ROBOT_SF_AUDIT_MCP_SESSION_TOKEN",
            "ROBOT_SF_AUDIT_MCP_ORIGIN",
        ]
        values = [
            f"{prefix}.command={json.dumps(command[0])}",
            f"{prefix}.args={json.dumps(list(command[1:]))}",
            f"{prefix}.env_vars={json.dumps(env_vars)}",
            f"{prefix}.required={'true' if self.required else 'false'}",
        ]
        return tuple(values)


@dataclass(frozen=True, slots=True)
class CodexAppServerConfig:
    """Bounded subprocess and protocol settings for one local adapter."""

    executable: str | None = None
    cwd: str | Path | None = None
    env: Mapping[str, str] | None = None
    mcp: AppServerMCPConfig | None = None
    client_name: str = DEFAULT_CLIENT_NAME
    client_version: str = DEFAULT_CLIENT_VERSION
    expected_cli_version: str = TESTED_CODEX_CLI_VERSION
    request_timeout_seconds: float = DEFAULT_REQUEST_TIMEOUT_SECONDS
    startup_timeout_seconds: float = DEFAULT_STARTUP_TIMEOUT_SECONDS
    lifetime_seconds: float = DEFAULT_LIFETIME_SECONDS
    close_timeout_seconds: float = DEFAULT_CLOSE_TIMEOUT_SECONDS
    max_frame_bytes: int = MAX_APP_SERVER_FRAME_BYTES
    max_events: int = MAX_APP_SERVER_EVENTS
    accounting_mode: str = "local_accounting"
    require_explicit_route: bool = False
    required_route_id: str = ""
    required_provider: str = ""
    required_model_id: str = ""
    provider_ceiling_verified: bool = False
    provider_compute_ceiling: float | None = None

    def __post_init__(self) -> None:  # noqa: C901
        """Validate timeout, frame, and client metadata bounds."""

        if self.cwd is not None and not isinstance(self.cwd, (str, Path)):
            raise ValueError("cwd must be a path or None")
        for name in (
            "request_timeout_seconds",
            "startup_timeout_seconds",
            "lifetime_seconds",
            "close_timeout_seconds",
        ):
            _finite_positive(getattr(self, name), name=name)
        if not isinstance(self.max_frame_bytes, int) or self.max_frame_bytes < 1_024:
            raise ValueError("max_frame_bytes must be at least 1024")
        if not isinstance(self.max_events, int) or self.max_events < 1:
            raise ValueError("max_events must be positive")
        _text(self.client_name, name="client_name")
        _text(self.client_version, name="client_version")
        _text(self.expected_cli_version, name="expected_cli_version")
        if self.accounting_mode not in {"offline", "local_accounting", "strict_provider_ceiling"}:
            raise ValueError("unsupported App Server accounting_mode")
        if not isinstance(self.require_explicit_route, bool):
            raise ValueError("require_explicit_route must be boolean")
        for name in ("required_route_id", "required_provider", "required_model_id"):
            value = getattr(self, name)
            if not isinstance(value, str):
                raise ValueError(f"{name} must be text")
            if value and any(char.isspace() for char in value):
                raise ValueError(f"{name} must not contain whitespace")
        if self.require_explicit_route and not (
            self.required_route_id and self.required_provider and self.required_model_id
        ):
            raise ValueError(
                "explicit-route mode requires required_route_id, required_provider, and "
                "required_model_id"
            )
        if not isinstance(self.provider_ceiling_verified, bool):
            raise ValueError("provider_ceiling_verified must be boolean")
        if self.provider_compute_ceiling is not None:
            _finite_positive(self.provider_compute_ceiling, name="provider_compute_ceiling")
        if self.accounting_mode == "strict_provider_ceiling" and (
            not self.provider_ceiling_verified or self.provider_compute_ceiling is None
        ):
            raise ValueError(
                "strict_provider_ceiling requires a verified provider_compute_ceiling"
            )
        if self.accounting_mode == "strict_provider_ceiling" and not self.require_explicit_route:
            raise ValueError("strict_provider_ceiling requires require_explicit_route=True")

    def resolve_executable(self) -> str:
        """Resolve an explicit or PATH-installed Codex executable."""

        candidate = self.executable or shutil.which("codex")
        if not candidate:
            raise AppServerUnavailable("Codex executable is not installed")
        path = Path(candidate)
        if path.is_absolute() and not path.exists():
            raise AppServerUnavailable(f"Codex executable does not exist: {candidate}")
        return candidate

    def command(self) -> tuple[str, ...]:
        """Build a shell-free App Server stdio command."""

        command = [self.resolve_executable(), "app-server", "--stdio"]
        if self.mcp is not None:
            for override in self.mcp.config_overrides():
                command.extend(("-c", override))
        return tuple(command)

    def process_environment(self) -> dict[str, str]:
        """Build process environment while keeping session credentials private."""

        result = dict(os.environ)
        result.pop(MCP_SESSION_TOKEN_ENV, None)
        if self.mcp is not None:
            result.update(self.mcp.bridge.environment(result))
        if self.env is not None:
            for key, value in self.env.items():
                if not isinstance(key, str) or not isinstance(value, str):
                    raise ValueError("App Server environment keys and values must be strings")
                if key == MCP_SESSION_TOKEN_ENV:
                    raise ValueError(
                        "App Server environment cannot override the audit session token"
                    )
                result[key] = value
        return result


class CodexAppServerTransport:
    """Thread-safe bounded JSONL process transport."""

    def __init__(
        self,
        config: CodexAppServerConfig | None = None,
        *,
        popen_factory: Callable[..., Any] | None = None,
    ) -> None:
        """Configure one process transport; spawning is lazy."""

        self.config = config or CodexAppServerConfig()
        self._popen_factory = popen_factory or subprocess.Popen
        self._process: Any | None = None
        self._reader_thread: threading.Thread | None = None
        self._stderr_thread: threading.Thread | None = None
        self._write_lock = threading.Lock()
        self._condition = threading.Condition()
        self._responses: dict[Any, Mapping[str, Any]] = {}
        self._events: deque[AppServerFrame] = deque(maxlen=self.config.max_events)
        self._sequence = 0
        self._next_request_id = 0
        self._started_at = 0.0
        self._failure: AppServerError | None = None
        self._stderr_tail: deque[str] = deque(maxlen=32)
        self._stopping = threading.Event()
        self._termination_complete = threading.Event()
        self._termination_complete.set()
        self._initialized = False
        self._watchdog_thread: threading.Thread | None = None

    @property
    def process(self) -> Any | None:
        """Expose the process for diagnostics without exposing credentials."""

        return self._process

    @property
    def initialized(self) -> bool:
        """Return whether the initialize/initialized handshake completed."""

        return self._initialized

    @property
    def failure(self) -> AppServerError | None:
        """Return the first terminal transport failure, if any."""

        return self._failure

    @property
    def is_alive(self) -> bool:
        """Return whether the process is live and has no terminal failure."""

        process = self._process
        if process is None or self._failure is not None:
            return False
        try:
            return process.poll() is None
        except (AttributeError, OSError):
            return False

    @property
    def last_sequence(self) -> int:
        """Return the latest received frame sequence number."""

        return self._sequence

    @property
    def stderr_tail(self) -> tuple[str, ...]:
        """Return a bounded diagnostic tail from process stderr."""

        return tuple(self._stderr_tail)

    def events_since(self, sequence: int = 0) -> tuple[AppServerFrame, ...]:
        """Return retained notifications in receive order."""

        return tuple(frame for frame in self._events if frame.sequence > sequence)

    def start(self) -> CodexAppServerTransport:
        """Spawn one bounded App Server process."""

        if self.is_alive:
            return self
        self.close()
        command = self.config.command()
        try:
            process = self._popen_factory(
                command,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                cwd=str(self.config.cwd) if self.config.cwd is not None else None,
                env=self.config.process_environment(),
                bufsize=0,
            )
        except (OSError, ValueError) as exc:
            raise AppServerUnavailable(f"could not start Codex App Server: {exc}") from exc
        self._process = process
        self._started_at = time.monotonic()
        self._failure = None
        self._termination_complete.clear()
        self._initialized = False
        self._stopping.clear()
        self._reader_thread = threading.Thread(
            target=self._read_stdout,
            daemon=True,
            name="codex-app-server-stdout",
        )
        self._reader_thread.start()
        self._stderr_thread = threading.Thread(
            target=self._read_stderr,
            daemon=True,
            name="codex-app-server-stderr",
        )
        self._stderr_thread.start()
        self._watchdog_thread = threading.Thread(
            target=self._watch_lifetime,
            daemon=True,
            name="codex-app-server-watchdog",
        )
        self._watchdog_thread.start()
        return self

    def initialize(self) -> Mapping[str, Any]:
        """Perform the required initialize/initialized handshake once."""

        self.start()
        if self._initialized:
            return {}
        result = self.request(
            "initialize",
            {
                "clientInfo": {
                    "name": self.config.client_name,
                    "version": self.config.client_version,
                },
                "capabilities": {"experimentalApi": True},
            },
            timeout_seconds=self.config.startup_timeout_seconds,
        )
        self.send_notification("initialized", {})
        self._initialized = True
        return result

    def send_notification(self, method: str, params: Mapping[str, Any] | None = None) -> None:
        """Send one bounded JSON-RPC notification."""

        self._write_message({"method": _text(method, name="method"), "params": dict(params or {})})

    def request(
        self,
        method: str,
        params: Mapping[str, Any] | None = None,
        *,
        timeout_seconds: float | None = None,
    ) -> Mapping[str, Any]:
        """Send a request and await its matching response id."""

        self.start()
        timeout = _finite_positive(
            timeout_seconds if timeout_seconds is not None else self.config.request_timeout_seconds,
            name="timeout_seconds",
        )
        deadline = time.monotonic() + timeout
        self._check_lifetime(deadline)
        with self._condition:
            self._next_request_id += 1
            request_id = self._next_request_id
        message = {
            "jsonrpc": "2.0",
            "id": request_id,
            "method": _text(method, name="method"),
            "params": dict(params or {}),
        }
        with self._condition:
            self._responses.pop(request_id, None)
        self._write_message(message)
        with self._condition:
            while request_id not in self._responses:
                self._check_lifetime(deadline)
                if self._failure is not None:
                    failure = self._failure
                    self._await_termination()
                    raise failure
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    self._fail(AppServerTimeout(f"App Server request timed out: {method}"))
                    raise AppServerTimeout(f"App Server request timed out: {method}")
                self._condition.wait(timeout=remaining)
            response = self._responses.pop(request_id)
        if "error" in response:
            error = response.get("error")
            if not isinstance(error, Mapping):
                raise AppServerProtocolError("App Server error response is malformed")
            raise AppServerRPCError(
                error.get("code", "unknown"), error.get("message", "error"), error.get("data")
            )
        result = response.get("result")
        if not isinstance(result, Mapping):
            raise AppServerProtocolError(f"App Server response for {method} has no result object")
        return dict(result)

    def wait_for_notification(
        self,
        predicate: Callable[[AppServerFrame], bool],
        *,
        after_sequence: int = 0,
        timeout_seconds: float | None = None,
    ) -> AppServerFrame:
        """Wait for an ordered notification matching ``predicate``."""

        timeout = _finite_positive(
            timeout_seconds if timeout_seconds is not None else self.config.request_timeout_seconds,
            name="timeout_seconds",
        )
        deadline = time.monotonic() + timeout
        observed = after_sequence
        with self._condition:
            while True:
                for frame in self._events:
                    if frame.sequence > observed:
                        observed = frame.sequence
                        if predicate(frame):
                            return frame
                self._check_lifetime(deadline)
                if self._failure is not None:
                    failure = self._failure
                    self._await_termination()
                    raise failure
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise AppServerTimeout("App Server notification wait timed out")
                self._condition.wait(timeout=remaining)

    def _check_lifetime(self, deadline: float | None = None) -> None:
        if self._started_at and time.monotonic() - self._started_at >= self.config.lifetime_seconds:
            failure = AppServerTimeout("Codex App Server process lifetime expired")
            self._fail(failure)
            self._await_termination()
            self._terminate_process()
            raise failure
        if deadline is not None and time.monotonic() >= deadline:
            failure = AppServerTimeout("Codex App Server operation deadline expired")
            self._fail(failure)
            self._await_termination()
            self._terminate_process()
            raise failure

    def _write_message(self, message: Mapping[str, Any]) -> None:
        encoded = _strict_json(message, limit=self.config.max_frame_bytes, name="App Server frame")
        process = self._process
        if process is None or not self.is_alive:
            failure = self._failure or AppServerProcessLost("Codex App Server process is not alive")
            self._fail(failure)
            self._await_termination()
            raise failure
        stdin = getattr(process, "stdin", None)
        if stdin is None:
            failure = AppServerProcessLost("Codex App Server stdin is unavailable")
            self._fail(failure)
            raise failure
        with self._write_lock:
            try:
                stdin.write(encoded + b"\n")
                stdin.flush()
            except (BrokenPipeError, OSError, ValueError) as exc:
                failure = AppServerProcessLost(f"Codex App Server stdin closed: {exc}")
                self._fail(failure)
                self._await_termination()
                raise failure from exc

    def _read_stdout(self) -> None:  # noqa: C901
        process = self._process
        stdout = getattr(process, "stdout", None)
        if stdout is None:
            self._fail(AppServerProcessLost("Codex App Server stdout is unavailable"))
            return
        while not self._stopping.is_set():
            try:
                line = stdout.readline(self.config.max_frame_bytes + 1)
            except (OSError, ValueError) as exc:
                self._fail(AppServerProcessLost(f"Codex App Server stdout failed: {exc}"))
                return
            if not line:
                if not self._stopping.is_set():
                    self._fail(AppServerProcessLost("Codex App Server stdout closed"))
                return
            if isinstance(line, str):
                raw = line.encode("utf-8")
            else:
                raw = bytes(line)
            if len(raw) > self.config.max_frame_bytes:
                self._fail(AppServerProtocolError("App Server frame exceeds the byte limit"))
                return
            try:
                message = json.loads(raw.rstrip(b"\r\n").decode("utf-8"))
            except (json.JSONDecodeError, UnicodeDecodeError) as exc:
                self._fail(AppServerProtocolError(f"App Server emitted malformed JSON: {exc}"))
                return
            if not isinstance(message, Mapping) or message.get("jsonrpc") not in {None, "2.0"}:
                self._fail(AppServerProtocolError("App Server frame must be a JSON-RPC object"))
                return
            with self._condition:
                self._sequence += 1
                frame = AppServerFrame(self._sequence, dict(message))
                if "id" in message:
                    if len(self._responses) >= self.config.max_events:
                        self._fail(AppServerProtocolError("App Server response limit reached"))
                        return
                    self._responses[message["id"]] = dict(message)
                else:
                    self._events.append(frame)
                self._condition.notify_all()

    def _read_stderr(self) -> None:
        process = self._process
        stderr = getattr(process, "stderr", None)
        if stderr is None:
            return
        while not self._stopping.is_set():
            try:
                line = stderr.readline(8_193)
            except (OSError, ValueError):
                return
            if not line:
                return
            if isinstance(line, bytes):
                line = line.decode("utf-8", errors="replace")
            self._stderr_tail.append(str(line)[:8_192])

    def _watch_lifetime(self) -> None:
        """Terminate an idle process when its configured lifetime expires."""

        if self._stopping.wait(timeout=self.config.lifetime_seconds):
            return
        process = self._process
        if process is None or self._stopping.is_set():
            return
        try:
            if process.poll() is not None:
                return
        except (AttributeError, OSError):
            return
        self._fail(AppServerTimeout("Codex App Server process lifetime expired"))

    def _fail(self, error: AppServerError) -> None:
        should_terminate = False
        with self._condition:
            if self._failure is None:
                self._failure = error
                should_terminate = True
                self._stopping.set()
            self._condition.notify_all()
        if should_terminate:
            # A protocol/lifetime failure must not leave a child running after
            # the caller has already received a fail-closed error.  SIGTERM is
            # advisory (a child may ignore it), so bounded reaping escalates to
            # SIGKILL before returning to the reader/watchdog/request thread.
            try:
                self._terminate_process(force_reap=True)
            finally:
                self._termination_complete.set()

    def _await_termination(self) -> None:
        """Wait for a concurrent failure path to finish bounded child reaping."""

        self._termination_complete.wait(timeout=2 * self.config.close_timeout_seconds)

    def _terminate_process(self, *, force_reap: bool = False) -> None:
        process = self._process
        if process is None:
            return
        try:
            process.terminate()
        except (AttributeError, OSError):
            if not force_reap:
                return
        if not force_reap:
            return
        try:
            process.wait(timeout=self.config.close_timeout_seconds)
            return
        except (AttributeError, subprocess.TimeoutExpired, OSError):
            pass
        try:
            process.kill()
        except (AttributeError, OSError):
            pass
        try:
            process.wait(timeout=self.config.close_timeout_seconds)
        except (AttributeError, subprocess.TimeoutExpired, OSError):
            pass

    def close(self) -> None:
        """Terminate and reap the process within a bounded deadline."""

        process = self._process
        if process is None:
            return
        self._stopping.set()
        stdin = getattr(process, "stdin", None)
        if stdin is not None:
            try:
                stdin.close()
            except (OSError, ValueError):
                pass
        try:
            process.terminate()
        except (AttributeError, OSError):
            pass
        try:
            process.wait(timeout=self.config.close_timeout_seconds)
        except (AttributeError, subprocess.TimeoutExpired, OSError):
            try:
                process.kill()
            except (AttributeError, OSError):
                pass
            try:
                process.wait(timeout=self.config.close_timeout_seconds)
            except (AttributeError, subprocess.TimeoutExpired, OSError):
                pass
        for thread in (self._reader_thread, self._stderr_thread, self._watchdog_thread):
            if thread is not None and thread is not threading.current_thread():
                thread.join(timeout=self.config.close_timeout_seconds)
        self._reader_thread = None
        self._stderr_thread = None
        self._watchdog_thread = None
        self._process = None
        self._initialized = False
        self._termination_complete.set()
        self._stopping.clear()

    def restart(self) -> Mapping[str, Any]:
        """Restart the process and perform a fresh initialize handshake."""

        self.close()
        self._failure = None
        return self.initialize()

    def __enter__(self) -> CodexAppServerTransport:
        """Start/use the transport in a context-managed scope."""

        return self

    def __exit__(self, *_: Any) -> None:
        """Close the transport at context exit."""

        self.close()


def _version(executable: str, *, timeout_seconds: float) -> str:
    """Read the installed CLI version without invoking a shell."""

    try:
        result = subprocess.run(
            [executable, "--version"],
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise AppServerUnavailable(f"could not inspect Codex version: {exc}") from exc
    if result.returncode != 0:
        raise AppServerUnavailable(f"Codex --version failed with exit {result.returncode}")
    text = (result.stdout or result.stderr or "").strip()
    if text.startswith("codex-cli "):
        return text.removeprefix("codex-cli ").split()[0]
    return text.split()[0] if text else ""


def _model_choice(
    result: Mapping[str, Any], *, requested_model_id: str = ""
) -> Mapping[str, Any]:
    data = result.get("data")
    if not isinstance(data, Sequence) or isinstance(data, (str, bytes)):
        raise AppServerUnavailable("model/list returned no model data")
    models = [
        item for item in data if isinstance(item, Mapping) and isinstance(item.get("id"), str)
    ]
    if requested_model_id:
        matches = [item for item in models if item.get("id") == requested_model_id]
        if len(matches) != 1:
            raise AppServerUnavailable("model/list did not expose the requested exact model")
        return matches[0]
    defaults = [item for item in models if item.get("isDefault") is True]
    if len(defaults) == 1:
        return defaults[0]
    if len(models) == 1:
        return models[0]
    raise AppServerUnavailable("model/list did not identify one actual default model")


def _thread_route(
    result: Mapping[str, Any],
    *,
    client_version: str,
    accounting_mode: str = "local_accounting",
    provider_ceiling_verified: bool = False,
) -> CodexRouteReceipt:
    model_id = result.get("model")
    provider = result.get("modelProvider")
    if not isinstance(model_id, str) or not model_id.strip():
        raise AppServerUnavailable("thread/start returned no actual model")
    if not isinstance(provider, str) or not provider.strip():
        raise AppServerUnavailable("thread/start returned no actual model provider")
    route_id = f"{provider}:{model_id}"
    return CodexRouteReceipt(
        route_id=route_id,
        provider=provider,
        model_id=model_id,
        client_version=client_version,
        protocol=APP_SERVER_PROTOCOL,
        source="live-app-server-capability",
        accounting_mode=accounting_mode,
        provider_ceiling_verified=provider_ceiling_verified,
        capability_digest=_digest(
            {
                "route_id": route_id,
                "provider": provider,
                "model_id": model_id,
                "client_version": client_version,
                "protocol": APP_SERVER_PROTOCOL,
                "schema_digest": APP_SERVER_SCHEMA_DIGEST,
            }
        ),
    )


def inspect_live_capabilities(
    config: CodexAppServerConfig | None = None,
    *,
    transport_factory: Callable[[CodexAppServerConfig], CodexAppServerTransport] | None = None,
) -> CodexCapabilityInspection:
    """Discover one actual local App Server route or return unavailable."""

    cfg = config or CodexAppServerConfig()
    inspector_name = f"codex-app-server/{cfg.expected_cli_version}"
    try:
        executable = cfg.resolve_executable()
        installed_version = _version(executable, timeout_seconds=cfg.startup_timeout_seconds)
        if installed_version != cfg.expected_cli_version:
            return CodexCapabilityInspection(
                "unavailable",
                inspector=inspector_name,
                reason=(
                    f"installed Codex version {installed_version or '<unknown>'} is not the "
                    f"tested {cfg.expected_cli_version}"
                ),
                installed=True,
            )
        transport = (
            transport_factory(cfg)
            if transport_factory is not None
            else CodexAppServerTransport(cfg)
        )
        try:
            transport.initialize()
            listed = transport.request("model/list", {"includeHidden": False, "limit": 100})
            model = _model_choice(listed, requested_model_id=cfg.required_model_id)
            params: dict[str, Any] = {
                "model": model["id"],
                "ephemeral": True,
                "approvalPolicy": "never",
                "sandbox": "read-only",
            }
            if cfg.cwd is not None:
                params["cwd"] = str(cfg.cwd)
            started = transport.request("thread/start", params)
            route = _thread_route(
                started,
                client_version=installed_version,
                accounting_mode=cfg.accounting_mode,
                provider_ceiling_verified=cfg.provider_ceiling_verified,
            )
            if cfg.required_route_id and route.route_id != cfg.required_route_id:
                raise AppServerUnavailable("discovered route does not match required_route_id")
            if cfg.required_provider and route.provider != cfg.required_provider:
                raise AppServerUnavailable("discovered route does not match required_provider")
            if cfg.required_model_id and route.model_id != cfg.required_model_id:
                raise AppServerUnavailable("discovered route does not match required_model_id")
            return CodexCapabilityInspection(
                "available",
                routes=(route,),
                inspector=inspector_name,
                installed=True,
            )
        finally:
            transport.close()
    except (AppServerError, ValueError, TypeError, KeyError) as exc:
        return CodexCapabilityInspection(
            "unavailable",
            inspector=inspector_name,
            reason=f"live App Server capability unavailable: {exc}",
            installed=bool(shutil.which("codex") or cfg.executable),
        )


class CodexAppServerProvider:
    """Implement the existing ``CodexProvider`` seam with App Server v2."""

    supports_tools = True

    def __init__(
        self,
        *,
        config: CodexAppServerConfig | None = None,
        bridge: AuditMCPBridge | None = None,
        transport: CodexAppServerTransport | None = None,
        popen_factory: Callable[..., Any] | None = None,
    ) -> None:
        """Configure a provider; no process is started until ``start``."""

        cfg = config or CodexAppServerConfig()
        if bridge is not None:
            cfg = replace(cfg, mcp=AppServerMCPConfig(bridge))
        self.config = cfg
        self.transport = transport or CodexAppServerTransport(cfg, popen_factory=popen_factory)
        self._turns: dict[str, str] = {}
        self._threads: dict[str, str] = {}
        self._lock = threading.RLock()

    @property
    def route_protocol(self) -> str:
        """Return the protocol name admitted by this provider."""

        return APP_SERVER_PROTOCOL

    def _check_route(self, route: CodexRouteReceipt) -> None:
        if route.protocol != APP_SERVER_PROTOCOL:
            raise AppServerUnavailable("route was not discovered from App Server v2")
        if route.client_version != self.config.expected_cli_version:
            raise AppServerUnavailable("route CLI version does not match the tested adapter")
        if route.accounting_mode != self.config.accounting_mode:
            raise AppServerUnavailable("route accounting mode does not match provider configuration")
        if route.provider_ceiling_verified != self.config.provider_ceiling_verified:
            raise AppServerUnavailable("route provider-ceiling evidence does not match configuration")
        if self.config.required_route_id and route.route_id != self.config.required_route_id:
            raise AppServerUnavailable("route does not match required_route_id")
        if self.config.required_provider and route.provider != self.config.required_provider:
            raise AppServerUnavailable("route does not match required_provider")
        if self.config.required_model_id and route.model_id != self.config.required_model_id:
            raise AppServerUnavailable("route does not match required_model_id")
        if self.config.accounting_mode == "strict_provider_ceiling" and (
            not self.config.provider_ceiling_verified
            or self.config.provider_compute_ceiling is None
        ):
            raise AppServerUnavailable(
                "strict provider-ceiling mode is unavailable without a verified provider ceiling"
            )

    @staticmethod
    def _require_turn_reservation(
        reserved_compute: float | None,
        *,
        accounting_mode: str = "local_accounting",
        provider_ceiling_verified: bool = False,
        provider_compute_ceiling: float | None = None,
    ) -> float:
        """Require authority pre-admission before an unmeasured model turn."""

        if accounting_mode == "offline":
            raise AppServerUnavailable("offline accounting mode refuses provider turns")
        if accounting_mode == "strict_provider_ceiling" and (
            not provider_ceiling_verified or provider_compute_ceiling is None
        ):
            raise AppServerUnavailable(
                "strict provider-ceiling mode requires a verified provider ceiling"
            )
        if isinstance(reserved_compute, bool) or not isinstance(reserved_compute, (int, float)):
            raise AppServerUnavailable(
                "unmeasured App Server turn requires reserved_compute >= "
                f"{UNMEASURED_TURN_COMPUTE_CHARGE} before provider work"
            )
        value = float(reserved_compute)
        if not math.isfinite(value) or value < UNMEASURED_TURN_COMPUTE_CHARGE:
            raise AppServerUnavailable(
                "unmeasured App Server turn requires reserved_compute >= "
                f"{UNMEASURED_TURN_COMPUTE_CHARGE} before provider work"
            )
        if (
            accounting_mode == "strict_provider_ceiling"
            and provider_compute_ceiling is not None
            and value > float(provider_compute_ceiling)
        ):
            raise AppServerUnavailable(
                "reserved_compute exceeds the verified provider compute ceiling"
            )
        return value

    def _thread_params(self, route: CodexRouteReceipt) -> dict[str, Any]:
        params: dict[str, Any] = {
            "model": route.model_id,
            # Provider lifecycle includes resume/reconnect.  Ephemeral threads
            # have no persisted rollout and fail ``thread/resume`` on the
            # installed App Server, so provider-owned threads are durable.
            "ephemeral": False,
            "approvalPolicy": "never",
            "sandbox": "read-only",
        }
        if self.config.cwd is not None:
            params["cwd"] = str(self.config.cwd)
        return params

    @staticmethod
    def _prompt_with_evidence(prompt: str, evidence: Sequence[Mapping[str, Any]]) -> str:
        """Bind compact evidence locators into the model-visible turn text."""

        lines = [prompt.strip(), "", "Audit evidence references (use the audit MCP tools):"]
        for item in evidence:
            if not isinstance(item, Mapping):
                continue
            evidence_id = str(item.get("evidence_id", ""))[:256]
            locator = str(item.get("locator", ""))[:1_024]
            if evidence_id or locator:
                lines.append(f"- {evidence_id}: {locator}")
        result = "\n".join(lines)
        if len(result) > MAX_EVIDENCE_PROMPT_CHARS:
            result = result[:MAX_EVIDENCE_PROMPT_CHARS]
        return result

    @staticmethod
    def _thread_id(result: Mapping[str, Any]) -> str:
        thread = result.get("thread")
        if not isinstance(thread, Mapping):
            raise AppServerProtocolError("App Server thread response has no thread object")
        return _text(thread.get("id"), name="thread.id")

    @staticmethod
    def _turn_id(result: Mapping[str, Any]) -> str:
        turn = result.get("turn")
        if not isinstance(turn, Mapping):
            raise AppServerProtocolError("App Server turn response has no turn object")
        return _text(turn.get("id"), name="turn.id")

    @staticmethod
    def _usage(frames: Sequence[AppServerFrame]) -> dict[str, Any]:
        """Extract telemetry and apply the bounded unmeasured-turn charge.

        The installed App Server emits token usage but no measured compute
        field.  Returning zero here would refund the service reservation and
        make repeated live turns free.  A successful turn therefore carries a
        finite one-unit accounting charge, explicitly marked as unmeasured;
        it is a budget guardrail, not a claim about provider compute.
        """

        latest: Mapping[str, Any] | None = None
        for frame in frames:
            if frame.message.get("method") != "thread/tokenUsage/updated":
                continue
            params = frame.message.get("params")
            if isinstance(params, Mapping) and isinstance(params.get("tokenUsage"), Mapping):
                latest = params["tokenUsage"]
        if latest is None:
            return {}
        last = latest.get("last")
        # `total` is cumulative across the durable thread. A fresh per-turn
        # reservation may only be settled from the last-turn meter.
        breakdown = last
        if not isinstance(breakdown, Mapping):
            return {}
        tokens = breakdown.get("totalTokens")
        if isinstance(tokens, bool) or not isinstance(tokens, int) or tokens < 0:
            return {}
        return {
            "tokens": tokens,
            "compute": UNMEASURED_TURN_COMPUTE_CHARGE,
            "issue_writes": 0,
            "compute_measured": False,
            "compute_basis": "bounded-per-turn-unmeasured-charge",
            "source": "thread/tokenUsage/updated",
        }

    def _run_turn(
        self,
        *,
        thread_id: str,
        input_text: str,
        provider_session_id: str,
    ) -> Mapping[str, Any]:
        before = self.transport.last_sequence
        started = self.transport.request(
            "turn/start",
            {"threadId": thread_id, "input": [{"type": "text", "text": input_text}]},
            timeout_seconds=self.config.request_timeout_seconds,
        )
        turn_id = self._turn_id(started)
        with self._lock:
            self._turns[provider_session_id] = turn_id
        completed = self.transport.wait_for_notification(
            lambda frame: (
                frame.message.get("method") == "turn/completed"
                and isinstance(frame.message.get("params"), Mapping)
                and isinstance(frame.message["params"].get("turn"), Mapping)
                and frame.message["params"]["turn"].get("id") == turn_id
            ),
            after_sequence=before,
            timeout_seconds=self.config.request_timeout_seconds,
        )
        with self._lock:
            self._turns.pop(provider_session_id, None)
        params = completed.message.get("params")
        turn = params.get("turn") if isinstance(params, Mapping) else None
        status = turn.get("status") if isinstance(turn, Mapping) else "failed"
        frames = self.transport.events_since(before)
        usage = self._usage(frames)
        if status != "completed":
            return {
                "status": "failed",
                "provider_session_id": provider_session_id,
                "reason": f"App Server turn ended with status {status}",
                "usage": self._annotate_accounting_usage(usage),
            }
        if not usage:
            raise AppServerProtocolError("App Server turn completed without token usage telemetry")
        return {
            "status": "complete",
            "provider_session_id": provider_session_id,
            "message": "Codex App Server turn completed",
            "usage": self._annotate_accounting_usage(usage),
            "event_count": len(frames),
        }

    def _annotate_accounting_usage(self, usage: Mapping[str, Any]) -> dict[str, Any]:
        """Expose accounting mode and the physical-cap evidence boundary."""

        result = dict(usage)
        result.update(
            {
                "accounting_mode": self.config.accounting_mode,
                "provider_ceiling_verified": self.config.provider_ceiling_verified,
                "physical_provider_cap_enforced": (
                    self.config.accounting_mode == "strict_provider_ceiling"
                ),
            }
        )
        if self.config.provider_compute_ceiling is not None:
            result["provider_compute_ceiling"] = self.config.provider_compute_ceiling
        return result

    def start(
        self,
        *,
        route: CodexRouteReceipt,
        prompt: str,
        evidence: Sequence[Mapping[str, Any]],
        reserved_compute: float | None = None,
    ) -> Mapping[str, Any]:
        """Start one bounded turn after authority reserves compute."""

        self._check_route(route)
        self._require_turn_reservation(
            reserved_compute,
            accounting_mode=self.config.accounting_mode,
            provider_ceiling_verified=self.config.provider_ceiling_verified,
            provider_compute_ceiling=self.config.provider_compute_ceiling,
        )
        self.transport.initialize()
        started = self.transport.request(
            "thread/start",
            self._thread_params(route),
            timeout_seconds=self.config.startup_timeout_seconds,
        )
        actual_model = started.get("model")
        actual_provider = started.get("modelProvider")
        if actual_model != route.model_id or actual_provider != route.provider:
            raise AppServerProtocolError(
                "App Server selected a route different from the discovered route"
            )
        thread_id = self._thread_id(started)
        with self._lock:
            self._threads[thread_id] = thread_id
        return self._run_turn(
            thread_id=thread_id,
            input_text=self._prompt_with_evidence(prompt, evidence),
            provider_session_id=thread_id,
        )

    def resume(
        self,
        *,
        provider_session_id: str,
        route: CodexRouteReceipt,
        evidence: Sequence[Mapping[str, Any]],
        reserved_compute: float | None = None,
    ) -> Mapping[str, Any]:
        """Resume a thread after authority reserves compute for the new turn."""

        self._check_route(route)
        self._require_turn_reservation(
            reserved_compute,
            accounting_mode=self.config.accounting_mode,
            provider_ceiling_verified=self.config.provider_ceiling_verified,
            provider_compute_ceiling=self.config.provider_compute_ceiling,
        )
        self.transport.initialize()
        resumed = self.transport.request(
            "thread/resume",
            {
                "threadId": _text(
                    self._threads.get(provider_session_id, provider_session_id), name="thread_id"
                ),
                "model": route.model_id,
            },
            timeout_seconds=self.config.request_timeout_seconds,
        )
        actual_model = resumed.get("model")
        actual_provider = resumed.get("modelProvider")
        if actual_model != route.model_id or actual_provider != route.provider:
            raise AppServerProtocolError("resumed thread route differs from the admitted route")
        thread_id = self._thread_id(resumed)
        with self._lock:
            self._threads[provider_session_id] = thread_id
        return self._run_turn(
            thread_id=thread_id,
            input_text=self._prompt_with_evidence(
                "Continue the scoped audit investigation from the existing Codex thread.", evidence
            ),
            provider_session_id=provider_session_id,
        )

    def reconnect(self, *, provider_session_id: str, route: CodexRouteReceipt) -> Mapping[str, Any]:
        """Reconnect a live transport or restart it before ``thread/resume``."""

        self._check_route(route)
        restarted = not self.transport.is_alive or not self.transport.initialized
        if restarted:
            self.transport.restart()
        resumed = self.transport.request(
            "thread/resume",
            {"threadId": _text(provider_session_id, name="thread_id"), "model": route.model_id},
            timeout_seconds=self.config.request_timeout_seconds,
        )
        if resumed.get("model") != route.model_id or resumed.get("modelProvider") != route.provider:
            raise AppServerProtocolError("reconnected thread route differs from the admitted route")
        return {
            "status": "complete",
            "provider_session_id": provider_session_id,
            "message": "Codex App Server transport reconnected",
            "restarted": restarted,
            "usage": self._annotate_accounting_usage(
                {"tokens": 0, "compute": 0.0, "issue_writes": 0}
            ),
        }

    def cancel(self, *, provider_session_id: str, route: CodexRouteReceipt) -> Mapping[str, Any]:
        """Interrupt the active turn and retain a cancellation receipt."""

        self._check_route(route)
        with self._lock:
            turn_id = self._turns.get(provider_session_id)
        if not turn_id:
            return {
                "status": "cancelled",
                "provider_session_id": provider_session_id,
                "message": "Codex App Server had no active turn",
                "usage": self._annotate_accounting_usage(
                    {"tokens": 0, "compute": 0.0, "issue_writes": 0}
                ),
            }
        with self._lock:
            thread_id = self._threads.get(provider_session_id, provider_session_id)
        self.transport.request(
            "turn/interrupt",
            {"threadId": thread_id, "turnId": turn_id},
            timeout_seconds=self.config.request_timeout_seconds,
        )
        return {
            "status": "cancelled",
            "provider_session_id": provider_session_id,
            "message": "Codex App Server turn interrupted",
            "usage": self._annotate_accounting_usage(
                {"tokens": 0, "compute": 0.0, "issue_writes": 0}
            ),
        }

    def close(self) -> None:
        """Close the process and any owned MCP bridge."""

        self.transport.close()
        if self.config.mcp is not None:
            self.config.mcp.bridge.close()

    def __enter__(self) -> CodexAppServerProvider:
        """Use the provider in a context-managed scope."""

        return self

    def __exit__(self, *_: Any) -> None:
        """Close the provider at context exit."""

        self.close()


