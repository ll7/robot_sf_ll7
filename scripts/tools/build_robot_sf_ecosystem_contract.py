    """Validate schema-specific authority declarations."""
    schema_inputs = [item for item in authority_ids if inputs[item].get("kind") == "json_schema"]
    if len(schema_inputs) != 1 or inputs[schema_inputs[0]].get("path") != location:
        raise ContractError(f"{label} must cite exactly one location-matching JSON schema")


