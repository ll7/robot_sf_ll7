"""Experimental local Codex App Server adapter for the audit workbench.

The adapter speaks the installed Codex App Server's newline-delimited JSON-RPC
protocol directly.  It performs the version-specific ``initialize`` handshake,
discovers an actual model/provider route through ``model/list`` and
``thread/start``, streams bounded notifications, and keeps all subprocess
lifetime decisions fail-closed.  Credentials remain in the Codex process
environment and never enter route/session receipts.

The tested contract is ``codex-cli 0.154.0`` with the experimental v2 schema
generated by ``codex app-server generate-json-schema --out <DIR> --experimental``.  App
Server is an experimental local capability; this module intentionally does not
claim production support.
"""

